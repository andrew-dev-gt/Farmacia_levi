CREATE TABLE IF NOT EXISTS `products` (
  `id` VARCHAR(100) NOT NULL PRIMARY KEY,
  `name` VARCHAR(255) NOT NULL,
  `presentation` VARCHAR(255) DEFAULT '',
  `description` TEXT,
  `category` VARCHAR(100) DEFAULT '',
  `price` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `lot` VARCHAR(100) DEFAULT '',
  `stock` JSON DEFAULT NULL,
  `expiryDates` JSON DEFAULT NULL,
  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `suppliers` (
  `id` VARCHAR(100) NOT NULL PRIMARY KEY,
  `companyName` VARCHAR(255) NOT NULL,
  `nit` VARCHAR(50) DEFAULT '',
  `type` VARCHAR(100) DEFAULT '',
  `phone` VARCHAR(50) DEFAULT '',
  `email` VARCHAR(150) DEFAULT '',
  `address` TEXT,
  `notes` TEXT,
  `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `purchases` (
  `id` VARCHAR(100) NOT NULL PRIMARY KEY,
  `supplierId` VARCHAR(100) DEFAULT NULL,
  `date` VARCHAR(50) DEFAULT '',
  `items` JSON DEFAULT NULL,
  `total` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `transfers` (
  `id` VARCHAR(100) NOT NULL PRIMARY KEY,
  `fromBranch` VARCHAR(100) DEFAULT '',
  `toBranch` VARCHAR(100) DEFAULT '',
  `items` JSON DEFAULT NULL,
  `date` VARCHAR(50) DEFAULT '',
  `status` VARCHAR(50) DEFAULT 'completed',
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `sales` (
  `id` VARCHAR(100) NOT NULL PRIMARY KEY,
  `branch` VARCHAR(100) DEFAULT '',
  `items` JSON DEFAULT NULL,
  `total` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `date` VARCHAR(50) DEFAULT '',
  `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
